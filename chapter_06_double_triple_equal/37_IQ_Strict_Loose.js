console.log(0 == "0"); //true
// == converts string '0' to number 0
console.log(0 == "");
// == converts empty string '' to number 0
console.log(0 === "0"); //false
// different datatype and different value
console.log("" == 0); //true
// == converts empty string '' to number 0
console.log("" === 0); //false
// different datatype and different value