//Compound Assignment Operators
let x = 10;
x += 10;//x=x+10
console.log(x); //return 20 because x is updated to 20 after adding 10 to the original value of 10   
x -= 3;//x=x-3
console.log(x);//return 17 because x is updated to 17 after subtracting 3 from the previous value of 20
x *= 2;//x=x*2
console.log(x);//return 34 because x is updated to 34 after multiplying the previous value of 17 by 2
x /= 17;//x=x/17
console.log(x);//return 2 because x is updated to 2 after dividing the previous value of 34 by 17
x %= 2;//x=x%2
console.log(x);//return 0 because x is updated to 0 after calculating the remainder of the previous value of 2 divided by 2