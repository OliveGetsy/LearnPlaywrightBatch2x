//Single quote string literal
let singleQuote = 'Hello, World!';
console.log('singleQuote:', singleQuote);
let withDoubleQuoteInside = 'She said, "Hello!"'; // String with double quotes inside
console.log('withDoubleQuoteInside:', withDoubleQuoteInside);

//Double quote string literal
let doubleQuote = "JavaScript is fun!";
console.log('doubleQuote:', doubleQuote);
let withSingleQuoteInside = "It's a nice day!"; // String with single quote inside
console.log('withSingleQuoteInside:', withSingleQuoteInside);

